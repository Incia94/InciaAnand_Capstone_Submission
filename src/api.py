# ------------------------------------------------------------------ the FastAPI app
def create_app(pipeline: Optional[SupportPipeline] = None) -> FastAPI:
    metrics = pipeline.metrics if pipeline and pipeline.metrics else Metrics()

    @asynccontextmanager
    async def lifespan(app):
        if getattr(app.state, "pipeline", None) is None:
            app.state.pipeline = SupportPipeline.from_env(metrics)
        yield

    app = FastAPI(title="CloudServe support pipeline", version="1.0",
                  description="Ingest, classify, retrieve, route, generate and guard customer tickets.",
                  lifespan=lifespan)
    if pipeline is not None:
        pipeline.metrics = pipeline.metrics or metrics
    app.state.pipeline = pipeline
    app.state.metrics = metrics

    @app.get("/health")
    def health(request: Request):
        p = request.app.state.pipeline
        info = p.health()
        problems = [k for k, ok in (("classifier", info["classifier"]["ready"]),
                                    ("decision_log", info["decision_log"]["healthy"])) if not ok]
        degraded = [k for k, bad in (("retrieval", info["retrieval"]["fallback_only"]),
                                     ("generator", info["generator"]["mode"] != "llm")) if bad]
        status = "down" if problems else ("degraded" if degraded or info["kill_switch"] else "ok")
        return {"status": status, "problems": problems, "degraded": degraded, **info}

    @app.get("/", include_in_schema=False)
    def root():
        return RedirectResponse(url="/docs")

    @app.post("/tickets", response_model=TicketOutcome, summary="Process one ticket from any channel",
              openapi_extra={"requestBody": {"required": True, "content": {"application/json": {
                  "schema": TICKET_SCHEMA, "examples": TICKET_EXAMPLES}}}})
    async def tickets(request: Request):
        """Accepts a ticket in the dataset's schema (or close to it). Malformed JSON or plain text
        is still processed: it becomes an unprocessable or plain-text ticket and is escalated."""
        body = await request.body()
        try:
            raw: Any = json.loads(body.decode("utf-8", errors="replace")) if body else {}
        except ValueError:
            raw = body.decode("utf-8", errors="replace")
        p = request.app.state.pipeline
        metrics.kill_switch.set(1 if kill_switch_active() else 0)
        run_id = request.headers.get("X-Run-Id")
        return p.process(raw, run_id=run_id)

    @app.get("/tickets/{ticket_id}/decisions")
    def decisions(ticket_id: str, request: Request):
        trail = request.app.state.pipeline.store.trail(ticket_id)
        if not trail:
            return JSONResponse(status_code=404, content={"detail": f"no decisions logged for {ticket_id}"})
        return {"ticket_id": ticket_id, "decisions": trail}

    @app.get("/metrics")
    def prometheus_metrics():
        return Response(generate_latest(metrics.registry), media_type=CONTENT_TYPE_LATEST)

    return app


def main(argv: Optional[list[str]] = None) -> int:
    try:
        from dotenv import load_dotenv
        load_dotenv()
    except ImportError:
        pass
    argv = sys.argv[1:] if argv is None else argv
    logging.basicConfig(level=os.getenv("LOG_LEVEL", "INFO"), format="%(levelname)s %(name)s: %(message)s")
    if argv[:1] == ["graph"]:          # python -m src.api graph  -> Mermaid diagram of the pipeline
        print(SupportPipeline.from_env().mermaid())
        return 0
    import uvicorn
    uvicorn.run(create_app(), host=os.getenv("API_HOST", "127.0.0.1"), port=int(os.getenv("API_PORT", "8000")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
