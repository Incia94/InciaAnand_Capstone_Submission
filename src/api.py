"""The FastAPI application, and the pipeline that runs one ticket from arrival to outcome.

Usage (run from the project root)
-----
    python -m src.api                        # serves on API_HOST:API_PORT (default 127.0.0.1:8000)
    open http://127.0.0.1:8000/docs          # interactive documentation, generated by FastAPI
    python -m src.api graph                  # the LangGraph pipeline as a Mermaid diagram

Endpoints
---------
GET  /health                       components loaded, which are degraded, kill switch state
POST /tickets                      process one ticket from any channel; returns the outcome
GET  /tickets/{ticket_id}/decisions  the decision trail for a ticket, from the decision log
GET  /metrics                      Prometheus metrics (see the Setup Guide's monitoring section)

The pipeline (orchestrated by LangGraph; see SupportPipeline)
------------
ingest -> classify -> retrieve -> route -> (generate -> guardrails) -> outcome

Every stage writes a row to the decision log (src/logging_store.py), and every ticket ends with
exactly one `outcome` row: "sent" (an automatic reply passed the guardrails) or "escalated" (with
the handoff a person needs). A ticket the guardrails block is escalated with the blocked draft's
findings attached. Nothing here raises for a bad ticket: malformed JSON, plain text, missing
fields or an internal error all end as a logged escalation with the reason (A11).

Kill switch: set KILL_SWITCH=1, or create the file named by KILL_SWITCH_FILE
(default ./storage/KILL_SWITCH). While it is on, every ticket is escalated and nothing is sent
automatically. It is read on every request, so it takes effect without a restart.
"""
